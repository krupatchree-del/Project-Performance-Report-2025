-- 1. ตารางด่านการเรียนรู้ (stages)
CREATE TABLE IF NOT EXISTS public.stages (
  id INTEGER PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT NOT NULL,
  description TEXT,
  formula_highlight TEXT,
  boss_name TEXT,
  theme_color TEXT,
  unlock_score INTEGER DEFAULT 0
);

-- 2. ตารางนักเรียน (students)
CREATE TABLE IF NOT EXISTS public.students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code TEXT DEFAULT '',
  name TEXT NOT NULL,
  class_room TEXT NOT NULL DEFAULT 'ม.4/1',
  student_number INTEGER DEFAULT 1,
  avatar TEXT DEFAULT '🧑‍🔬',
  total_score INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. ตารางคลังโจทย์เคมี (questions)
CREATE TABLE IF NOT EXISTS public.questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stage_id INTEGER NOT NULL REFERENCES public.stages(id) ON DELETE CASCADE,
  topic TEXT NOT NULL,
  difficulty INTEGER DEFAULT 1,
  question_type TEXT DEFAULT 'choice',
  question_text TEXT NOT NULL,
  chemical_formula TEXT DEFAULT '',
  given_atomic_masses TEXT DEFAULT '',
  choices JSONB DEFAULT '[]'::jsonb,
  correct_answer TEXT NOT NULL,
  numeric_answer DOUBLE PRECISION,
  hint TEXT DEFAULT '',
  explanation TEXT DEFAULT '',
  points INTEGER DEFAULT 100,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. ตารางความก้าวหน้ารายด่านของนักเรียน (stage_progress)
CREATE TABLE IF NOT EXISTS public.stage_progress (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  stage_id INTEGER NOT NULL REFERENCES public.stages(id) ON DELETE CASCADE,
  best_score INTEGER DEFAULT 0,
  stars INTEGER DEFAULT 0,
  accuracy_pct DOUBLE PRECISION DEFAULT 0,
  attempts_count INTEGER DEFAULT 1,
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(student_id, stage_id)
);

-- 5. ตารางบันทึกประวัติการทำโจทย์รายข้อสำหรับงานวิจัย (attempt_logs)
CREATE TABLE IF NOT EXISTS public.attempt_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  stage_id INTEGER NOT NULL REFERENCES public.stages(id) ON DELETE CASCADE,
  question_id BIGINT,
  topic TEXT DEFAULT '',
  student_answer TEXT DEFAULT '',
  is_correct BOOLEAN DEFAULT FALSE,
  points_earned INTEGER DEFAULT 0,
  time_spent_sec DOUBLE PRECISION DEFAULT 0,
  used_hint BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

